import json
from typing import Dict, Any


def generate_json_report(report_dict: Dict[str, Any]) -> str:
    """Formats investigation result into JSON matching exact required schema."""
    output_schema_keys = [
        "engine_id",
        "failure_detected",
        "failure_type",
        "confidence",
        "timeline",
        "root_cause",
        "evidence",
        "affected_components",
        "what_if"
    ]
    clean_dict = {k: report_dict[k] for k in output_schema_keys if k in report_dict}
    return json.dumps(clean_dict, indent=2)


def generate_text_report(report_dict: Dict[str, Any]) -> str:
    """Formats investigation result into a human-readable text summary."""
    engine_id = report_dict.get("engine_id", "Unknown")
    failure_detected = report_dict.get("failure_detected", False)
    failure_type = report_dict.get("failure_type", "N/A")
    confidence = report_dict.get("confidence", 0.0)
    root_cause = report_dict.get("root_cause", "N/A")
    evidence = report_dict.get("evidence", [])
    components = report_dict.get("affected_components", [])
    what_if = report_dict.get("what_if", {})
    timeline = report_dict.get("timeline", [])

    total_cycles = len(timeline)
    initial_state = timeline[0]["state"] if timeline else "Normal"
    final_state = timeline[-1]["state"] if timeline else "Normal"
    final_score = timeline[-1]["anomaly_score"] if timeline else 0.0

    evidence_str = "\n".join([f"  - {e}" for e in evidence]) if evidence else "  - No specific sensor anomalies detected."
    components_str = ", ".join(components) if components else "None identified."

    report_text = f"""================================================================================
INDUSTRIAL MACHINE FAILURE INVESTIGATION REPORT
Target Asset: Turbofan Engine #{engine_id}
================================================================================

1. EXECUTIVE SUMMARY
--------------------
- Status: {"CRITICAL / FAILURE DETECTED" if failure_detected else "NORMAL OPERATIONAL STATE"}
- Primary Diagnosis: {failure_type}
- Diagnostic Confidence: {confidence * 100:.1f}%
- Cumulative Cycles Logged: {total_cycles} cycles
- Current Health State: {final_state} (Latest Anomaly Score: {final_score:.6f})

2. ROOT CAUSE INFERENCE & COMPONENT ANALYSIS
---------------------------------------------
- Probable Root Cause: {root_cause}
- Key Supporting Evidence:
{evidence_str}
- Primary Affected Sub-Components: {components_str}

3. HEALTH DEGRADATION TIMELINE SUMMARY
--------------------------------------
- Initial Cycle State: {initial_state}
- Final Cycle State: {final_state}
- Transition Summary: Asset progressed over {total_cycles} operational cycles from {initial_state} state to {final_state} state.

4. COUNTERFACTUAL WHAT-IF SIMULATION
------------------------------------
- Scenario: {what_if.get('scenario', 'N/A')}
- Projected Outcome: {what_if.get('result', 'N/A')}

================================================================================
Report Generated by Antigravity Industrial Failure Investigator
================================================================================
"""
    return report_text
